//! CHIMERA's calibrated vowel postures (its `phonetics/vowelTargets.generated.json`, generated
//! by `chimera calibrate vowels`): for each body, 26 vowels' articulations fitted with the
//! frequency-domain airway to reference formants (Hillenbrand et al. 1995 for the English
//! vowels, literature values for the others), and the formants the fitted posture gives.
//!
//! The inversion uses them as the plausible postures its prior centres on and as seeds of its
//! codebook; the tests use them as sung-vowel articulations to invert. The values are
//! CHIMERA's, digit for digit (the tongue tip as CHIMERA's planner sets it, `ttCurl` the rhotic
//! curl of ɝ and ʅ).

use crate::anatomy::{BodyName, HumanArtic, NEUTRAL};

/// One calibrated vowel.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct CalibratedVowel {
    /// Its IPA symbol (Mandarin's retracted u̠ ʊ̠ carry U+0320).
    pub ipa: &'static str,
    /// The fitted articulation (template coordinates, as [`HumanArtic`]).
    pub artic: HumanArtic,
    /// F1–F4 (Hz) of that articulation, as CHIMERA's calibration read them.
    pub formants: [f64; 4],
}

/// The calibrated vowels of `body`.
pub fn calibrated(body: BodyName) -> &'static [CalibratedVowel] {
    match body {
        BodyName::Male => &table::MALE,
        BodyName::Female => &table::FEMALE,
        BodyName::Child => &table::CHILD,
    }
}

/// The vowel `ipa` of `body`, if the table has it.
pub fn vowel(body: BodyName, ipa: &str) -> Option<&'static CalibratedVowel> {
    calibrated(body).iter().find(|v| v.ipa == ipa)
}

/// A row: jaw, tbX, tbY, ttX, ttY, ttCurl, root, lipAp, lipProt, lipWidth, larynx.
const fn row(ipa: &'static str, p: [f64; 11], formants: [f64; 4]) -> CalibratedVowel {
    CalibratedVowel {
        ipa,
        artic: HumanArtic {
            jaw: p[0],
            tb_x: p[1],
            tb_y: p[2],
            tt_x: p[3],
            tt_y: p[4],
            tt_curl: p[5],
            root: p[6],
            lip_ap: p[7],
            lip_prot: p[8],
            lip_width: p[9],
            larynx: p[10],
            ..NEUTRAL
        },
        formants,
    }
}

