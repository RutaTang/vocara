import 'audio_fx.dart';

/// A named vocal effect preset (one-tap good sound). [description] is a one-line
/// summary of the character / use-case.
class FxPreset {
  const FxPreset(this.name, this.description, this.fx);
  final String name;
  final String description;
  final TrackFx fx;
}

/// A named shared-reverb preset.
class ReverbPreset {
  const ReverbPreset(this.name, this.reverb);
  final String name;
  final ReverbSettings reverb;
}

/// Builds a full-chain [TrackFx] from per-plugin on-flags + settings. The 6 EQ
/// gains map onto the fixed band layout the engine expects (low shelf 100 Hz,
/// peaks 250 / 700 / 2k / 6k, high shelf 12k). Any plugin left off keeps its
/// default (no-op) settings.
TrackFx _fx({
  // EQ (6 fixed bands; gains in dB).
  bool eqOn = false,
  double low = 0,
  double lowMid = 0,
  double mid = 0,
  double highMid = 0,
  double presence = 0,
  double high = 0,
  // Other inserts: each is bypassed unless its on-flag is set.
  bool compOn = false,
  CompSettings comp = const CompSettings(),
  bool deEsserOn = false,
  DeEsserSettings deEsser = const DeEsserSettings(),
  bool gateOn = false,
  GateSettings gate = const GateSettings(),
  bool delayOn = false,
  DelaySettings delay = const DelaySettings(),
  bool saturationOn = false,
  SaturationSettings saturation = const SaturationSettings(),
  bool doublerOn = false,
  DoublerSettings doubler = const DoublerSettings(),
  bool limiterOn = false,
  LimiterSettings limiter = const LimiterSettings(),
  bool reverbOn = false,
  ReverbSettings reverb = const ReverbSettings(),
}) => TrackFx(
  eq: [
    EqBand(kind: EqBandKind.lowShelf, freq: 100, q: 0.7, gainDb: low),
    EqBand(kind: EqBandKind.peaking, freq: 250, q: 1.0, gainDb: lowMid),
    EqBand(kind: EqBandKind.peaking, freq: 700, q: 1.0, gainDb: mid),
    EqBand(kind: EqBandKind.peaking, freq: 2000, q: 1.0, gainDb: highMid),
    EqBand(kind: EqBandKind.peaking, freq: 6000, q: 1.0, gainDb: presence),
    EqBand(kind: EqBandKind.highShelf, freq: 12000, q: 0.7, gainDb: high),
  ],
  eqOn: eqOn,
  comp: comp,
  compOn: compOn,
  deEsser: deEsser,
  deEsserOn: deEsserOn,
  gate: gate,
  gateOn: gateOn,
  delay: delay,
  delayOn: delayOn,
  saturation: saturation,
  saturationOn: saturationOn,
  doubler: doubler,
  doublerOn: doublerOn,
  limiter: limiter,
  limiterOn: limiterOn,
  reverb: reverb,
  reverbOn: reverbOn,
);

